/**
 * Upsert student into Supabase students table
 */
export async function syncStudentToSupabase(student: {
  student_id: string;
  full_name: string;
  class_number: number;
  roll_number: number;
  gender: string;
  guardian_name?: string;
  guardian_phone?: string;
  email?: string;
  address?: string;
  admission_date?: string;
  status?: string;
}): Promise<{ success: boolean; error?: string }> {
  try {
    const { error } = await supabase.from('students').upsert(
      {
        student_id: student.student_id,
        full_name: student.full_name,
        class_number: student.class_number,
        roll_number: student.roll_number,
        gender: student.gender,
        guardian_name: student.guardian_name || '',
        guardian_phone: student.guardian_phone || '',
        email: student.email || '',
        address: student.address || '',
        admission_date: student.admission_date || null,
        status: student.status || 'active',
        updated_at: new Date().toISOString(),
      },
      { onConflict: 'student_id' }
    );

    if (error) {
      console.warn('[Supabase Sync] Student upsert notice:', error.message);
      return { success: false, error: error.message };
    }
    return { success: true };
  } catch (err: any) {
    console.warn('[Supabase Sync] Error during student sync:', err.message);
    return { success: false, error: err.message };
  }
}

/**
 * Delete student from Supabase
 */
export async function deleteStudentFromSupabase(studentId: string): Promise<void> {
  try {
    await supabase.from('attendance').delete().eq('student_id', studentId);
    await supabase.from('students').delete().eq('student_id', studentId);
  } catch (err) {
    console.warn('[Supabase Sync] Failed to delete from Supabase:', err);
  }
}

/**
 * Upsert attendance batch into Supabase attendance table
 */
export async function syncAttendanceBatchToSupabase(
  records: Array<{
    student_id: string;
    class_number: number;
    date: string;
    status: string;
    remarks: string;
    marked_by: string;
    updated_at: string;
  }>
): Promise<{ success: boolean; count: number; error?: string }> {
  if (!records.length) return { success: true, count: 0 };
  try {
    const payload = records.map((r) => ({
      student_id: r.student_id,
      class_number: r.class_number,
      date: r.date,
      status: r.status,
      remarks: r.remarks || '',
      marked_by: r.marked_by || 'admin',
      updated_at: r.updated_at,
    }));

    const { error } = await supabase.from('attendance').upsert(payload, {
      onConflict: 'student_id,date',
    });

    if (error) {
      console.warn('[Supabase Sync] Attendance upsert notice:', error.message);
      return { success: false, count: 0, error: error.message };
    }

    return { success: true, count: records.length };
  } catch (err: any) {
    console.warn('[Supabase Sync] Failed to sync attendance to Supabase:', err.message);
    return { success: false, count: 0, error: err.message };
  }
}

/**
 * Check connection status to Supabase
 */
export async function checkSupabaseStatus(): Promise<{
  connected: boolean;
  tablesReady: boolean;
  message: string;
}> {
  try {
    const { error } = await supabase.from('students').select('student_id').limit(1);
    if (!error) {
      return {
        connected: true,
        tablesReady: true,
        message: `Connected to Supabase project ${PROJECT_ID} (all tables live and ready).`,
      };
    }

    if (error.code === 'PGRST205') {
      return {
        connected: true,
        tablesReady: false,
        message: `Connected to Supabase project ${PROJECT_ID}. Please run the provided SQL in Supabase SQL editor to create the tables.`,
      };
    }

    return {
      connected: false,
      tablesReady: false,
      message: `Supabase status: ${error.message}`,
    };
  } catch (err: any) {
    return {
      connected: false,
      tablesReady: false,
      message: err.message || 'Could not connect to Supabase endpoint.',
    };
  }
}

/**
 * Hydrate local database cache from remote Supabase on startup
 */
export async function pullSupabaseData(
  runSql: (sql: string, params?: any[]) => any
): Promise<{ studentsCount: number; attendanceCount: number }> {
  let studentsCount = 0;
  let attendanceCount = 0;

  try {
    const { data: remoteStudents, error: sErr } = await supabase.from('students').select('*');
    if (!sErr && remoteStudents && remoteStudents.length > 0) {
      const now = new Date().toISOString();
      for (const s of remoteStudents) {
        if (!s.student_id || !s.full_name) continue;
        runSql(
          `INSERT OR REPLACE INTO students (
            student_id, full_name, class_number, roll_number, gender, guardian_name, guardian_phone, email, address, admission_date, status, created_at, updated_at
          ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          [
            s.student_id,
            s.full_name,
            s.class_number || 1,
            s.roll_number || 1,
            s.gender || 'Male',
            s.guardian_name || '',
            s.guardian_phone || '',
            s.email || '',
            s.address || '',
            s.admission_date || now.split('T')[0],
            s.status || 'active',
            s.created_at || now,
            s.updated_at || now,
          ]
        );
        studentsCount++;
      }
    }

    const { data: remoteAttendance, error: aErr } = await supabase.from('attendance').select('*');
    if (!aErr && remoteAttendance && remoteAttendance.length > 0) {
      const now = new Date().toISOString();
      for (const a of remoteAttendance) {
        if (!a.student_id || !a.date || !a.status) continue;
        runSql(
          `INSERT OR REPLACE INTO attendance (student_id, class_number, date, status, remarks, marked_by, updated_at)
           VALUES (?, ?, ?, ?, ?, ?, ?)`,
          [
            a.student_id,
            a.class_number || 1,
            a.date,
            a.status,
            a.remarks || '',
            a.marked_by || 'admin',
            a.updated_at || now,
          ]
        );
        attendanceCount++;
      }
    }
  } catch (err: any) {
    console.warn('[Supabase Sync] Background cache pull notice:', err.message);
  }

  return { studentsCount, attendanceCount };
}
